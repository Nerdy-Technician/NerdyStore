// Fill a listing's docker-compose template with host defaults (PUID/PGID, TZ, data path)
// and build a matching .env, all in the browser. Pure string work so it runs under node --test.

export const DEFAULT_PUID = "1000";
export const DEFAULT_PGID = "1000";
export const DEFAULT_TZ = "Europe/London";
export const DEFAULT_BASE_PATH = "/opt/appdata";

export const browserTimeZone = () => {
    try {
        return Intl.DateTimeFormat().resolvedOptions().timeZone || DEFAULT_TZ;
    } catch {
        return DEFAULT_TZ;
    }
};

const ID_PATTERN = /^\d{1,10}$/;
const TZ_PATTERN = /^[A-Za-z0-9_+\-/]{1,64}$/;

export const sanitizeId = (value, fallback) => (ID_PATTERN.test(String(value ?? "").trim()) ? String(value).trim() : fallback);
export const sanitizeTimeZone = (value) => (TZ_PATTERN.test(String(value ?? "").trim()) ? String(value).trim() : DEFAULT_TZ);

// Absolute or ~ path, no spaces/quotes/colons (colons would break the volume spec). Trailing slashes dropped.
export const sanitizeBasePath = (value) => {
    const trimmed = String(value ?? "").trim().replace(/\/+$/, "");
    if (!trimmed || !/^(~|\/)[A-Za-z0-9._\-/~]*$/.test(trimmed) || trimmed.includes("..")) return DEFAULT_BASE_PATH;
    return trimmed;
};

export const appDataPath = (basePath, appId) => `${sanitizeBasePath(basePath)}/${String(appId || "app").replace(/[^a-z0-9._-]/gi, "-")}`;

// `- KEY=value` list items and `KEY: value` map entries.
const setEnvValue = (text, keys, value) => {
    const names = keys.join("|");
    return text
        .replace(new RegExp(`^([ \\t]*-[ \\t]*["']?)(${names})=([^"'\\n]*)(["']?)[ \\t]*$`, "gm"), (_, pre, key, _old, quote) => `${pre}${key}=${value}${quote}`)
        .replace(new RegExp(`^([ \\t]+)(${names}):[ \\t]*\\S.*$`, "gm"), (_, indent, key) => `${indent}${key}: "${value}"`);
};

// Relative bind mounts (`- ./config:/config`, `- ./data:/data:ro`) move under the data path.
const rewriteBindMounts = (text, dataPath) =>
    text.replace(/^([ \t]*-[ \t]*["']?)\.\/([^:"'\n]*):/gm, (_, pre, rel) => `${pre}${dataPath}${rel ? `/${rel.replace(/\/+$/, "")}` : ""}:`)
        .replace(/^([ \t]*-[ \t]*["']?)\.:/gm, (_, pre) => `${pre}${dataPath}:`);

export const fillCompose = (template, options = {}) => {
    const puid = sanitizeId(options.puid, DEFAULT_PUID);
    const pgid = sanitizeId(options.pgid, DEFAULT_PGID);
    const tz = sanitizeTimeZone(options.tz);
    const dataPath = appDataPath(options.basePath, options.appId);
    let out = String(template ?? "");
    out = setEnvValue(out, ["PUID", "USER_ID", "UID"], puid);
    out = setEnvValue(out, ["PGID", "GROUP_ID", "GID"], pgid);
    out = setEnvValue(out, ["TZ", "[A-Z0-9_]*_TIME_ZONE", "[A-Z0-9_]*_TIMEZONE", "GENERIC_TIMEZONE"], tz);
    // linuxserver-style images read TZ too; add it next to PGID when the template omits it.
    if (!/^\s*-\s*["']?TZ=/m.test(out) && !/^\s+TZ:/m.test(out)) out = out.replace(/^([ \t]*-[ \t]*["']?)PGID=[^\n]*$/m, (line, pre) => `${line}\n${pre}TZ=${tz}${pre.endsWith('"') || pre.endsWith("'") ? pre.slice(-1) : ""}`);
    out = rewriteBindMounts(out, dataPath);
    return out;
};

// ${VAR}, ${VAR:-default}, ${VAR-default}, ${VAR:?msg}, ${VAR?msg}
const VAR_PATTERN = /\$\{([A-Za-z_][A-Za-z0-9_]*)(?:(:?[-?])([^}]*))?\}/g;

export const composeVariables = (template) => {
    const vars = new Map();
    for (const [, name, op, rest] of String(template ?? "").matchAll(VAR_PATTERN)) {
        if (vars.has(name)) continue;
        vars.set(name, { name, required: Boolean(op && op.includes("?")), defaultValue: op && op.includes("-") ? rest : "" });
    }
    return [...vars.values()];
};

const parseEnvExample = (text) => {
    const values = new Map();
    for (const line of String(text ?? "").split("\n")) {
        const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/);
        if (m) values.set(m[1], m[2].trim());
    }
    return values;
};

const ENV_OVERRIDES = { PUID: "puid", PGID: "pgid", TZ: "tz" };

// .env for the filled compose: committed .env.example values first, then compose defaults.
// Secrets that are still placeholders stay visible so the user replaces them before `up`.
export const buildEnvFile = (template, envExample, options = {}) => {
    const example = parseEnvExample(envExample);
    const filled = { puid: sanitizeId(options.puid, DEFAULT_PUID), pgid: sanitizeId(options.pgid, DEFAULT_PGID), tz: sanitizeTimeZone(options.tz) };
    const names = [...new Set([...example.keys(), ...composeVariables(template).map(v => v.name)])];
    if (!names.length) return "";
    const defaults = Object.fromEntries(composeVariables(template).map(v => [v.name, v]));
    const lines = ["# Generated by NerdyStore compose preview. Replace placeholder values (change-me, replace-with-...) before starting."];
    for (const name of names) {
        const override = ENV_OVERRIDES[name];
        const value = override ? filled[override] : example.has(name) ? example.get(name) : defaults[name]?.defaultValue || (defaults[name]?.required ? "change-me" : "");
        lines.push(`${name}=${value}`);
    }
    return lines.join("\n") + "\n";
};

export const composeFileName = (appId) => `${String(appId || "app").replace(/[^a-z0-9._-]/gi, "-")}-docker-compose.yml`;
